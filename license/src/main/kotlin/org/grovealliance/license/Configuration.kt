package org.grovealliance.license

import org.grovealliance.core.ConfigurationBuilder
import org.grovealliance.core.DependenciesGraph
import org.grovealliance.core.coroutines.Concurrency
import org.grovealliance.core.viewmodel.viewModel
import org.grovealliance.license.internal.LicenseInformationMapper
import org.grovealliance.license.internal.LicenseInformationMapperImpl
import org.grovealliance.license.internal.LicenseInformationSource
import org.grovealliance.license.internal.LicenseInformationSourceImpl
import org.grovealliance.license.internal.LicenseInformationViewModel

/**
 * Registers the license module within a Grove [ConfigurationBuilder], so that
 * [LicenseInformationScreen] can list the app and the third-party software it is built with.
 *
 * By default the dependencies are read from the list that the AboutLibraries Gradle plugin
 * generates into the app's resources, which requires the app to apply that plugin.
 *
 * Example usage:
 * ```kotlin
 * license {
 *     project {
 *         LicenseProject(
 *             name = StringResource(R.string.app_name),
 *             version = dependency<AppRevision>().version,
 *             licenseIdentifier = "MIT",
 *             url = "https://github.com/example/app",
 *         )
 *     }
 * }
 * ```
 */
fun ConfigurationBuilder.license(
    builder: LicenseConfigurationBuilder.() -> Unit,
) {
    val configuration = LicenseConfigurationBuilder().apply(builder).build()
    singleton { configuration }
    factory<LicenseInformationSource> {
        LicenseInformationSourceImpl(
            context = appContext(),
            graph = this,
            configuration = dependency(),
            ioDispatcher = dependency<Concurrency>().ioDispatcher(),
        )
    }
    factory<LicenseInformationMapper> { LicenseInformationMapperImpl() }
    viewModel {
        LicenseInformationViewModel(
            savedStateHandle = savedStateHandle(),
            source = dependency(),
            mapper = dependency(),
        )
    }
}

/**
 * Configures the license module before it is registered.
 *
 * A [project] must be supplied. The [dependencies] default to the list generated by the
 * AboutLibraries Gradle plugin.
 */
class LicenseConfigurationBuilder {
    private var project: (suspend DependenciesGraph.() -> LicenseProject)? = null
    private var dependencies: (suspend DependenciesGraph.() -> List<Dependency>)? = null

    /**
     * The app itself, listed above its dependencies.
     *
     * Resolved each time the screen reads its content, with the dependency graph as receiver.
     */
    fun project(project: suspend DependenciesGraph.() -> LicenseProject) {
        this.project = project
    }

    /**
     * Replaces the generated list with the given dependencies, listed in the order returned.
     *
     * Resolved each time the screen reads its content, with the dependency graph as receiver.
     */
    fun dependencies(dependencies: suspend DependenciesGraph.() -> List<Dependency>) {
        this.dependencies = dependencies
    }

    internal fun build(): LicenseConfiguration = LicenseConfiguration(
        project = requireNotNull(project) { "A license project must be provided." },
        dependencies = dependencies,
    )
}

internal data class LicenseConfiguration(
    val project: suspend DependenciesGraph.() -> LicenseProject,
    val dependencies: (suspend DependenciesGraph.() -> List<Dependency>)?,
)
