    protocol = load(catalogs, "exchange-protocol.json")
    policy = protocol["referencePolicy"]
    known = set(exchange_resource_types(protocol))

    def types(values):
        if any(value not in known for value in values):
            raise ValueError(f"unknown reference target in {values!r}")
        return "setOf(" + ", ".join(f"ResourceType.{snake_constant(value)}" for value in values) + ")"

    lines = [HEADER, "package org.grovealliance.fhir.contract", ""]
    lines += kdoc(["The references the exchange governs, generated from `exchange-protocol.json`."], 0)
    lines += ["@InternalGroveFhirApi", "object ReferencePolicy {", ""]
    lines += kdoc(
        [
            "A governed reference: the element [path] of a [resourceType] points only to one of [targetTypes].",
            "",
            "@property isRepeating whether the element holds a list of references",
        ],
        4,
    )
    lines += [
        "    data class GovernedPath(",
        "        val resourceType: ResourceType,",
        "        val path: String,",
        "        val isRepeating: Boolean,",
        "        val targetTypes: Set<ResourceType>,",
        "    )",
        "",
    ]
    lines += kdoc(["Every governed reference path."], 4)
    lines.append("    val paths: List<GovernedPath> = listOf(")
    for path in policy["paths"]:
        lines += [
            "        GovernedPath(",
            f"            resourceType = ResourceType.{snake_constant(path['resourceType'])},",
            f"            path = {kotlin_string(path['path'])},",
            f"            isRepeating = {str(path['repeating']).lower()},",
            f"            targetTypes = {types(path['targetTypes'])},",
            "        ),",
        ]
    lines += ["    )", ""]
    lines += kdoc(["The resource types each governed reference extension, by its url, may point to."], 4)
    lines.append("    val extensionTargets: Map<String, Set<ResourceType>> = mapOf(")
    for target in policy["extensionTargets"]:
        lines.append(f"        {kotlin_string(target['url'])} to {types(target['targetTypes'])},")
    lines += ["    )", ""]
    lines += kdoc(["The code systems an identifier-only Patient reference never states as its system."], 4)
    lines.append("    val reservedPatientSystems: Set<String> = setOf(")
    lines += [f"        {kotlin_string(system)}," for system in policy["identifierOnlyPatient"]["reservedSystems"]]
    lines += ["    )", "}"]
    return "\n".join(lines) + "\n"


