ENVELOPE_RESOURCE_TYPES = ["Bundle", "Provenance"]


def snake_constant(value):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", value).upper()


def exchange_resource_types(protocol):
    """Every resource type the exchange names: its envelope, its entries and every governed reference target."""
    policy = protocol["lifecycle"]["active"]["entryResourcePolicy"]
    names = set(ENVELOPE_RESOURCE_TYPES) | set(policy["outputResourceTypes"]) | set(policy["supportingResourceTypes"])
    for path in protocol["referencePolicy"]["paths"]:
        names.add(path["resourceType"])
        names.update(path["targetTypes"])
    for target in protocol["referencePolicy"]["extensionTargets"]:
        names.update(target["targetTypes"])
    for name in names:
        if not re.fullmatch(r"[A-Z][A-Za-z]+", name):
            raise ValueError(f"{name!r} is no FHIR resource type")
    return sorted(names)


