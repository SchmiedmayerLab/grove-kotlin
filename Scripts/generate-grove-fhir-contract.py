def constant_name(value):
    return re.sub(r"[^A-Za-z0-9]+", "_", value).upper()


def function_name(value):
    parts = re.split(r"[^A-Za-z0-9]+", value)
    return parts[0].lower() + "".join(part[:1].upper() + part[1:] for part in parts[1:])


def fsh_concepts(path, code_system_id):
    """The concepts of the FSH CodeSystem `code_system_id` in `path`, code to display, in order."""
    concepts, inside = {}, False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("Id: "):
            inside = line[4:].strip() == code_system_id
            continue
        if inside and line.startswith(("CodeSystem:", "ValueSet:", "Extension:", "Profile:", "Instance:", "Invariant:")):
            inside = False
        match = re.match(r'^\* #(\S+) "([^"]*)"', line) if inside else None
        if match:
            concepts[match.group(1)] = match.group(2)
    if not concepts:
        raise ValueError(f"{path} states no concepts for CodeSystem {code_system_id}")
    return concepts


