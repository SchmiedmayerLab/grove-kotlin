def fsh_definitions(guide, source, kind):
    """The ids of every FSH definition of `kind` (`CodeSystem` or `Extension`) the guide of `source` states, in order."""
    ids = []
    for path in sorted((guide / source / "input" / "fsh").glob("*.fsh")):
        inside = False
        for line in path.read_text(encoding="utf-8").splitlines():
            if re.match(r"^[A-Za-z]+:", line) and not line.startswith(("Id:", "Title:", "Description:", "Parent:", "Context:")):
                inside = line.startswith(f"{kind}:")
                continue
            if inside and line.startswith("Id: "):
                ids.append(line[4:].strip())
                inside = False
    return ids


def canonicals(catalogs, name, kind, segment, doc):
    graph = load(catalogs, "package-graph.json")
    guide = catalogs.parent
    lines = [HEADER, "package org.grovealliance.fhir.contract", ""]
    lines += kdoc(doc, 0)
    lines.append(f"object {name} {{")
    for package in graph["packages"]:
        if not (guide / package["source"] / "input" / "fsh").is_dir():
            continue
        ids = fsh_definitions(guide, package["source"], kind)
        if not ids:
            continue
        if len(set(ids)) != len(ids):
            raise ValueError(f"duplicate {kind} ids in {package['source']}")
        lines.append("")
        lines += kdoc([f"Defined by the `{package['packageId']}` package."], 4)
        lines.append(f"    object {package_object(package['source'])} {{")
        for definition in ids:
            lines.append(f"        const val {constant_name(definition)} = {kotlin_string(package['canonical'] + '/' + segment + '/' + definition)}")
        lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


