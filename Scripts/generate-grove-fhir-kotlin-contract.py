def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog-directory", type=Path, required=True)
    parser.add_argument("--repository-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    catalogs = Catalogs(arguments.catalog_directory.resolve())
    generated = outputs(catalogs, arguments.repository_root.resolve())
    if arguments.check:
        stale = False
        for path, content in generated.items():
            actual = path.read_text(encoding="utf-8") if path.exists() else ""
            if actual != content:
                print(f"error: {path} is not synchronized with the grove-fhir catalogs", file=sys.stderr)
                stale = True
        return int(stale)
    for path, content in generated.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
