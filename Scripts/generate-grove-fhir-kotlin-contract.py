# --- Kotlin rendering helpers -------------------------------------------------------------------


def kotlin_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    return f'"{escaped}"'


def wrapped_string(value: str, indent: int) -> str:
    """Render one string as `+` joined chunks so no generated line exceeds the lint limit."""
    if len(value) <= LINE_WIDTH:
        return kotlin_string(value)
    chunks: list[str] = []
    current = ""
    for word in value.split(" "):
        candidate = word if not current else f"{current} {word}"
        if len(candidate) > LINE_WIDTH and current:
            chunks.append(current + " ")
            current = word
        else:
            current = candidate
    chunks.append(current)
    joiner = " +\n" + " " * indent
    return joiner.join(kotlin_string(chunk) for chunk in chunks)


def constant_name(identifier: str, suffix: str = "", prefix: str | None = None, strip: str | None = None) -> str:
    """`grove-mobile-heart-rate` becomes `MOBILE_HEART_RATE_PROFILE`."""
    stem = re.sub(strip or r"^(grove-mobile-|grove-|health-connect-)", "", identifier)
    if prefix is None:
        prefix = "MOBILE" if identifier.startswith(("grove-mobile-", "grove-")) else "HEALTH_CONNECT"
    body = re.sub(r"[^A-Za-z0-9]+", "_", stem).strip("_").upper()
    return f"{prefix}_{body}{suffix}"


def enum_name(token: str) -> str:
    """`ActiveCaloriesBurned`, `active-calories-burned` and `Vo2Max` all become upper snake case."""
    spaced = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", token)
    return re.sub(r"[^A-Za-z0-9]+", "_", spaced).strip("_").upper()


def constant_type(value: str) -> str:
    if value.startswith('"') or value.startswith("$") or "." in value and not value.rstrip("L").isdigit():
        return "String"
    if value.endswith("L") and value[:-1].isdigit():
        return "Long"
    if value.isdigit():
        return "Int"
    raise SystemExit(f"cannot infer the constant type of {value!r}")


def declaration(name: str, value: str, doc: str = "", visibility: str = "public ") -> str:
    line = f"    {visibility}const val {name}: {constant_type(value)} = {value}"
    prefix = f"\n    /** {doc} */\n" if doc else ""
    if len(line) <= 120:
        return prefix + line
    return prefix + f"    {visibility}const val {name}: {constant_type(value)} =\n        {value}"


def string_set(name: str, values: list[str], indent: int = 4, visibility: str = "public ") -> list[str]:
    pad = " " * indent
    lines = [f"{pad}{visibility}val {name}: Set<String> = setOf("]
    lines.extend(f"{pad}    {kotlin_string(value)}," for value in values)
    lines.append(f"{pad})")
    return lines


def kotlin_decimal(value: int | float | None) -> str:
    if value is None:
        return "null"
    return f"java.math.BigDecimal({kotlin_string(json.dumps(value, allow_nan=False))})"


def render_coding(coding: dict[str, Any], indent: int) -> str:
    display = coding.get("display")
    pad = " " * indent
    return (
        "CatalogCoding(\n"
        f"{pad}    system = {kotlin_string(coding['system'])},\n"
        f"{pad}    code = {kotlin_string(coding['code'])},\n"
        f"{pad}    display = {kotlin_string(display) if display else 'null'},\n"
        f"{pad})"
    )


def render_value_domain(domain: dict[str, Any], indent: int) -> str:
    pad = " " * indent
    minimum = domain.get("minimum")
    maximum = domain.get("maximum")
    return (
        "QuantityValueDomain(\n"
        f"{pad}    minimum = {kotlin_decimal(minimum.get('value') if minimum else None)},\n"
        f"{pad}    maximum = {kotlin_decimal(maximum.get('value') if maximum else None)},\n"
        f"{pad}    integerOnly = {str(domain.get('integerOnly', False)).lower()},\n"
        f"{pad})"
    )


