def health_connect_outputs(catalogs: Catalogs) -> list[str]:
    return sorted(
        {
            output["measurement"]
            for record in catalogs.health_connect["recordTypes"]
            for output in record.get("outputs", [])
        }
    )


def produced_measurement(catalogs: Catalogs, identifier: str) -> dict[str, Any]:
    adapter = {row["id"]: row for row in catalogs.health_connect["adapterMeasurements"]}
    measurements = {row["id"]: row for row in catalogs.measurements["measurements"]}
    row = adapter.get(identifier, measurements.get(identifier))
    if row is None:
        raise SystemExit(f"{identifier}: the Health Connect adapter emits an output no catalog defines")
    return row


def measurement_profile(catalogs: Catalogs, row: dict[str, Any]) -> str:
    profile = row["profile"]
    if profile.startswith("https://"):
        return profile
    return measurement_canonical(catalogs, row)


