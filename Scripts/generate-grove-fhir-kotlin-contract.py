def output_role(catalogs: Catalogs, output: dict[str, Any]) -> tuple[str, str, str | None]:
    """The output role token, retraction role and graph rule of one catalog output."""
    rules = catalogs.health_connect["identity"]["sourceOutput"]["outputDiscriminatorRules"]
    count_rule = output["countRule"]
    if count_rule == "graph-specific":
        graph_rule = catalogs.health_connect["graphRules"][output["graphRule"]]
        structured = [item for item in graph_rule["outputs"] if item["resourceRole"] != "synthesized-specimen"]
        if len(structured) != 1:
            raise SystemExit(f"{output['graphRule']}: expected one structured graph output")
        child = structured[0]["resourceRole"] == "workout-child"
        return structured[0]["outputRole"], "child-output" if child else "primary-output", output["graphRule"]
    if count_rule not in rules:
        raise SystemExit(f"{count_rule}: no output discriminator rule")
    role = rules[count_rule].split(";", 1)[0].removeprefix("output-role ").strip()
    child = count_rule == "one-per-stage"
    return role, "child-output" if child else "primary-output", None


def generate_health_connect_source_type(catalogs: Catalogs) -> str:
    records = catalogs.health_connect["recordTypes"]
    statuses = catalogs.health_connect["statusVocabulary"]
    count_rules = catalogs.health_connect["outputCountRules"]
    if len(records) != catalogs.health_connect["source"]["recordTypeCount"]:
        raise SystemExit("The Health Connect record inventory count no longer matches its rows")
    tokens = [record["token"] for record in records]
    if len(set(tokens)) != len(tokens) or any(not token.endswith("Record") for token in tokens):
        raise SystemExit("Health Connect record tokens must be unique AndroidX Record class names")
    lines: list[str] = [
        "@file:OptIn(androidx.health.connect.client.feature.ExperimentalMindfulnessSessionApi::class)",
        "",
        f"package {ADAPTER_PACKAGE}",
        "",
        "import androidx.health.connect.client.records.Record",
        "import org.grovealliance.fhir.RetractionTargetRole",
        "import org.hl7.fhir.r4.model.ResourceType",
        "import kotlin.reflect.KClass",
        "",
        "/** How the adapter catalog classifies one AndroidX Record class. */",
        "public enum class HealthConnectSourceStatus(public val code: String) {",
    ]
    for status in statuses:
        lines.append(f"    {enum_name(status)}({kotlin_string(status)}),")
    lines.extend(
        [
            "}",
            "",
            "/** The closed output-count rules of the adapter catalog. */",
            "public enum class HealthConnectOutputCountRule(public val code: String) {",
        ]
    )
    for rule in count_rules:
        lines.append(f"    {enum_name(rule)}({kotlin_string(rule)}),")
    lines.extend(
        [
            "}",
            "",
            "/** Every AndroidX Health Connect Record class the adapter catalog inventories. */",
            "public enum class HealthConnectSourceType(",
            "    public val token: String,",
            "    public val recordClass: KClass<out Record>,",
            "    public val status: HealthConnectSourceStatus,",
            ") {",
        ]
    )
    for record in records:
        lines.append(
            f"    {enum_name(record['token'].removesuffix('Record'))}(\n"
            f"        token = {kotlin_string(record['token'])},\n"
            f"        recordClass = androidx.health.connect.client.records.{record['token']}::class,\n"
            f"        status = HealthConnectSourceStatus.{enum_name(record['status'])},\n"
            "    ),"
        )
    lines.extend(
        [
            "    ;",
            "",
            "    public companion object {",
            "        private val byClass: Map<KClass<out Record>, HealthConnectSourceType> =",
            "            entries.associateBy { it.recordClass }",
            "",
            "        /** The catalog source type of a record, or null for a Record class outside the inventory. */",
            "        public fun of(record: Record): HealthConnectSourceType? = byClass[record::class]",
            "",
            "        /** The catalog source type a token names, or null when the inventory has no such token. */",
            "        public fun of(token: String): HealthConnectSourceType? = entries.firstOrNull { it.token == token }",
            "    }",
            "}",
            "",
            "/** The adapter catalog rows, keyed by source type. */",
            "public object HealthConnectCatalog {",
            "    /** Every inventoried source type with its status, outputs and admitted contexts. */",
            "    public val entries: Map<HealthConnectSourceType, HealthConnectCatalogEntry> =",
            "        CATALOG_ENTRIES.associateBy { it.type }",
            "",
            "    /** The catalog row of one source type. */",
            "    public operator fun get(type: HealthConnectSourceType): HealthConnectCatalogEntry = entries.getValue(type)",
            "",
            "    /** Every output the catalog admits for one source type. */",
            "    public fun outputs(type: HealthConnectSourceType): List<HealthConnectOutput> = get(type).outputs",
            "",
            "    /** Every public source field of every supported type with its reviewed disposition. */",
            "    public val fieldDispositions: Map<HealthConnectSourceType, Map<String, HealthConnectFieldDisposition>>",
            "        get() = HealthConnectFieldDispositions.records",
            "}",
            "",
            "private val CATALOG_ENTRIES: List<HealthConnectCatalogEntry> = listOf(",
        ]
    )
    for record in records:
        source_type = enum_name(record["token"].removesuffix("Record"))
        contexts = ", ".join(kotlin_string(context) for context in record.get("context", []))
        reason = record.get("reason")
        lines.append("    HealthConnectCatalogEntry(")
        lines.append(f"        type = HealthConnectSourceType.{source_type},")
        lines.append(f"        status = HealthConnectSourceStatus.{enum_name(record['status'])},")
        lines.append(f"        contexts = setOf({contexts}),")
        lines.append(f"        reason = {wrapped_string(reason, 12) if reason else 'null'},")
        outputs = record.get("outputs", [])
        if not outputs:
            lines.append("        outputs = emptyList(),")
        else:
            lines.append("        outputs = listOf(")
            specimen_rendered = False
            for item in outputs:
                role, retraction_role, graph_rule = output_role(catalogs, item)
                arguments = [
                    f"measurement = {kotlin_string(item['measurement'])}",
                    "resourceType = ResourceType.Observation",
                    f"countRule = HealthConnectOutputCountRule.{enum_name(item['countRule'])}",
                    f"outputRole = {kotlin_string(role)}",
                    f"retractionRole = RetractionTargetRole.{enum_name(retraction_role)}",
                    f"graphRule = {kotlin_string(graph_rule) if graph_rule else 'null'}",
                    f"condition = {kotlin_string(item['when']) if item.get('when') else 'null'}",
                ]
                lines.append("            HealthConnectOutput(")
                lines.extend(f"                {argument}," for argument in arguments)
                lines.append("            ),")
                if graph_rule is None or specimen_rendered:
                    continue
                specimen = [
                    entry
                    for entry in catalogs.health_connect["graphRules"][graph_rule]["outputs"]
                    if entry["resourceRole"] == "synthesized-specimen"
                ]
                if specimen:
                    specimen_rendered = True
                    lines.append("            HealthConnectOutput(")
                    lines.append("                measurement = null,")
                    lines.append("                resourceType = ResourceType.Specimen,")
                    lines.append("                countRule = HealthConnectOutputCountRule.GRAPH_SPECIFIC,")
                    lines.append(f"                outputRole = {kotlin_string(specimen[0]['outputRole'])},")
                    lines.append("                retractionRole = RetractionTargetRole.SPECIMEN,")
                    lines.append(f"                graphRule = {kotlin_string(graph_rule)},")
                    lines.append("                condition = null,")
                    lines.append("            ),")
            lines.append("        ),")
        lines.append("    ),")
    lines.extend([")", ""])
    return HEADER + "\n".join(lines)


def generate_health_connect_measurements(catalogs: Catalogs) -> str:
    produced = health_connect_outputs(catalogs)
    adapter_measurements = {row["id"]: row for row in catalogs.health_connect["adapterMeasurements"]}
    lines: list[str] = [
        f"package {ADAPTER_PACKAGE}",
        "",
        "import org.grovealliance.fhir.QuantityValueDomain",
        "",
        "/** Every measurement the Health Connect adapter emits, keyed by its catalog id. */",
        "internal object HealthConnectMeasurements {",
        "    val byId: Map<String, MeasurementSpec> = MEASUREMENTS.associateBy { it.id }",
        "",
        "    /** The output measurements the catalog admits, keyed by the profile each claims. */",
        "    val byProfile: Map<String, MeasurementSpec> = HealthConnectCatalog.entries.values",
        "        .flatMap { it.outputs }",
        "        .mapNotNull { it.measurement }",
        "        .toSet()",
        "        .associate { byId.getValue(it).profile to byId.getValue(it) }",
        "",
        "    fun spec(id: String): MeasurementSpec = byId.getValue(id)",
        "}",
        "",
        "private val MEASUREMENTS: List<MeasurementSpec> = listOf(",
    ]
    for identifier in produced:
        row = produced_measurement(catalogs, identifier)
        adapter_specific = identifier in adapter_measurements or row.get("owner") == "health-connect"
        category = row.get("category")
        quantity = row.get("quantity")
        components = row.get("components") or []
        required = row.get("requiredCodings") or []
        effective = row.get("effective")
        if effective not in EFFECTIVE_SHAPES:
            raise SystemExit(f"{identifier}: unknown effective shape {effective!r}")
        value_kind = row.get("valueKind") or ("quantity" if quantity else "codeableConcept")
        if value_kind not in ("quantity", "codeableConcept", "components"):
            raise SystemExit(f"{identifier}: unknown value kind {value_kind!r}")
        lines.append("    MeasurementSpec(")
        lines.append(f"        id = {kotlin_string(identifier)},")
        lines.append(f"        profile = {kotlin_string(measurement_profile(catalogs, row))},")
