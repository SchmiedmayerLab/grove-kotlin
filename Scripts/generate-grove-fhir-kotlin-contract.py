def quantity_semantics(catalogs: Catalogs) -> dict[str, tuple[str, str]]:
    result: dict[str, tuple[str, str]] = {}
    for row in catalogs.measurements["measurements"]:
        quantity = row.get("quantity")
        if isinstance(quantity, dict):
            result[measurement_canonical(catalogs, row)] = (quantity["system"], quantity["code"])
    for row in catalogs.health_connect["adapterMeasurements"]:
        quantity = row.get("quantity")
        if isinstance(quantity, dict):
            result[row["profile"]] = (quantity["system"], quantity["code"])
    return dict(sorted(result.items()))


def value_domain(quantity: Any) -> dict[str, Any] | None:
    domain = quantity.get("valueDomain") if isinstance(quantity, dict) else None
    if not isinstance(domain, dict):
        return None
    for label in ("minimum", "maximum"):
        boundary = domain.get(label)
        if boundary is not None and boundary.get("inclusive") is not True:
            raise SystemExit(f"exclusive {label} cannot be projected by QuantityValueDomain")
    return domain


def rule_rows(catalogs: Catalogs) -> list[dict[str, Any]]:
    rows = catalogs.protocol["producerDiagnostics"]
    codes = [row["code"] for row in rows]
    if len(set(codes)) != len(codes):
        raise SystemExit("exchange-protocol producer diagnostic codes must be unique")
    for row in rows:
        if row.get("severity", "error") not in ("error", "warning"):
            raise SystemExit(f"{row['code']}: unknown severity {row.get('severity')!r}")
        if not re.fullmatch(r"[a-z][a-z0-9-]*\.[a-z][a-z0-9-]*", row["code"]):
            raise SystemExit(f"{row['code']}: rule codes are <namespace>.<rule> tokens")
    return rows


