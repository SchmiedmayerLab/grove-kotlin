def fsh_code_systems(guide_directory: Path) -> dict[str, list[tuple[str, str]]]:
    """Every CodeSystem a guide publishes with its concepts, read from the FSH sources."""
    fsh = guide_directory / "input" / "fsh"
    sources = sorted(fsh.glob("*.fsh"))
    if not sources:
        raise SystemExit(f"{fsh} holds no FSH; the contract cannot be projected from it")
    found: dict[str, list[tuple[str, str]]] = {}
    for source in sources:
        declared: str | None = None
        identifier: str | None = None
        for line in source.read_text(encoding="utf-8").splitlines():
            header = re.match(r"^CodeSystem:\s+(\S+)", line)
            if header:
                if declared and identifier is None:
                    raise SystemExit(f"{source}: CodeSystem {declared} declares no Id")
                declared, identifier = header.group(1), None
                continue
            if re.match(r"^[A-Za-z]+:\s", line) and not line.startswith(("Id:", "Title:", "Description:")):
                if declared and identifier is None:
                    raise SystemExit(f"{source}: CodeSystem {declared} declares no Id")
                declared, identifier = None, None
                continue
            if declared and line.startswith("Id:"):
                identifier = line.split(":", 1)[1].strip()
                found.setdefault(identifier, [])
                continue
            concept = re.match(r'^\* #(\S+) "((?:[^"\\]|\\.)*)"', line)
            if declared and identifier and concept:
                found[identifier].append((concept.group(1), concept.group(2).replace('\\"', '"')))
        if declared and identifier is None:
            raise SystemExit(f"{source}: CodeSystem {declared} declares no Id")
    if not found:
        raise SystemExit(f"{fsh} declares no CodeSystem; the contract would silently lose them")
    return dict(sorted(found.items()))


def concept_displays(code_systems: dict[str, list[tuple[str, str]]], identifier: str) -> dict[str, str]:
    concepts = code_systems.get(identifier)
    if not concepts:
        raise SystemExit(f"CodeSystem {identifier} declares no concepts")
    return dict(concepts)


