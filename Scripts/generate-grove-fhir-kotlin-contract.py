def identity_roles(catalogs: Catalogs, displays: dict[str, str]) -> list[tuple[str, str]]:
    roles: list[str] = []
    for kind in catalogs.protocol["opaqueIdentity"]["identityKinds"]:
        role = kind["identifierRole"]
        if role not in roles:
            roles.append(role)
    roles.extend(role for role in ("event", "entry-node") if role not in roles)
    return [(role, displays[role]) for role in roles]


def identity_kinds(catalogs: Catalogs) -> list[dict[str, Any]]:
    kinds = catalogs.protocol["opaqueIdentity"]["identityKinds"]
    names = [row.get("kind") for row in kinds]
    if len(set(names)) != len(names) or any(not isinstance(name, str) for name in names):
        raise SystemExit("The exchange protocol identity kinds must be unique tokens")
    return kinds


def unsigned_decimal_components(catalogs: Catalogs) -> list[str]:
    opaque = catalogs.protocol["opaqueIdentity"]
    names = opaque["componentRequirements"].get("unsignedDecimal")
    declared = {component for kind in opaque["identityKinds"] for component in kind["components"]}
    if not isinstance(names, list) or not names or len(set(names)) != len(names) or not set(names) <= declared:
        raise SystemExit("componentRequirements.unsignedDecimal must name distinct identity-kind components")
    return names


def recommended_forms(catalogs: Catalogs) -> dict[str, str]:
    protocol = catalogs.protocol
    forms = {
        "OPAQUE_IDENTITY_SYSTEM_FORM": protocol["opaqueIdentity"].get("recommendedSystemForm"),
        "EVENT_IDENTITY_SYSTEM_FORM": protocol["event"]["bundleIdentifier"].get("recommendedSystemForm"),
        "ENTRY_NODE_IDENTITY_SYSTEM_FORM": protocol["entryIdentity"]["entryNode"].get("recommendedSystemForm"),
    }
    for name, form in forms.items():
        if not isinstance(form, str) or "<deployment-root>" not in form:
            raise SystemExit(f"The exchange protocol must declare {name} with a <deployment-root> placeholder")
    if "<identity-kind>" not in forms["OPAQUE_IDENTITY_SYSTEM_FORM"]:
        raise SystemExit("The opaque identity system form must carry the <identity-kind> placeholder")
    return forms


def value_form_prefix(value_form: Any, label: str) -> str:
    if not isinstance(value_form, str):
        raise SystemExit(f"The exchange protocol must declare a {label} value form")
    prefix = value_form.split(":", 1)[0]
    if re.fullmatch(r"[a-z][a-z0-9]*", prefix) is None:
        raise SystemExit(f"The {label} value form must start with a lowercase protocol token")
    return prefix


def protocol_string(value: Any, label: str, pattern: str) -> str:
    if not isinstance(value, str) or re.fullmatch(pattern, value) is None:
        raise SystemExit(f"The exchange protocol must declare a well-formed {label}")
    return value


def adapter_only_output_profiles(catalogs: Catalogs) -> dict[str, str]:
    contract = catalogs.protocol["lifecycle"]["active"]["adapterOnlyOutputProfileClaims"]
    if contract.get("authority") != "catalog/profile-claims.json":
        raise SystemExit("adapterOnlyOutputProfileClaims must name catalog/profile-claims.json as its authority")
    resource_types = contract.get("resourceTypes")
    if not isinstance(resource_types, list) or len(resource_types) != len(set(resource_types)):
        raise SystemExit("adapterOnlyOutputProfileClaims.resourceTypes must be a unique string list")
    candidates: dict[str, list[dict[str, Any]]] = {resource_type: [] for resource_type in resource_types}

    def visit(value: Any) -> None:
        if isinstance(value, dict):
            resource_type = value.get("resourceType")
            if resource_type in candidates and isinstance(value.get("profile"), str):
                candidates[resource_type].append(value)
            for child in value.values():
                visit(child)
        elif isinstance(value, list):
            for child in value:
                visit(child)

    visit(catalogs.claims)
    profiles: dict[str, str] = {}
    for resource_type in resource_types:
        matches = candidates[resource_type]
        if len(matches) != 1:
            raise SystemExit(f"{resource_type}: expected exactly one adapter-only claim, found {len(matches)}")
        claim = matches[0]
        if claim.get("cardinality") != 1 or claim.get("otherProfilesAllowed") is not False:
            raise SystemExit(f"{resource_type}: adapter-only claim must require one exact profile and no others")
        profiles[resource_type] = claim["profile"]
    return dict(sorted(profiles.items()))


def measurement_canonical(catalogs: Catalogs, measurement: dict[str, Any]) -> str:
    owner = measurement.get("owner", "mobile")
    return f"{catalogs.graph['canonicalRoot']}/{owner}/StructureDefinition/{measurement['profile']}"


def profile_claims(catalogs: Catalogs) -> dict[str, Any]:
    claims = catalogs.claims
    protocol = catalogs.protocol
    active = protocol["lifecycle"]["active"]
    device_modes: dict[str, list[str]] = {}
    for claim in claims["activeDeviceClaims"]:
        profiles = claim.get("profiles")
        if (
            claim.get("resourceType") != "Device"
            or claim.get("cardinality") != 1
            or claim.get("otherProfilesAllowed") is not False
            or not isinstance(profiles, list)
            or len(profiles) != 1
        ):
            raise SystemExit("Every active Device claim must be one exact closed profile")
        device_modes[profiles[0]] = claim.get("requiredIdentifierRoles", [])
    document_modes: list[tuple[list[str], list[str]]] = []
    for key in (
        "sensorRecordingDocumentClaim",
        "healthKitRecordingDocumentClaim",
        "healthKitClinicalRecordDocumentClaim",
        "sensorKitRecordingDocumentClaim",
        "providerRecordingDocumentClaim",
    ):
        claim = claims[key]
        profiles = claim.get("profiles")
        if (
            claim.get("resourceType", "DocumentReference") != "DocumentReference"
            or claim.get("cardinality") != len(profiles or [])
            or claim.get("otherProfilesAllowed") is not False
            or not profiles
        ):
            raise SystemExit("Every active DocumentReference claim must be an exact closed profile set")
        document_modes.append((sorted(profiles), claim.get("requiredIdentifierRoles", [])))
    questionnaire = claims["activeQuestionnaireResponseClaim"]
    if questionnaire.get("cardinality") != 1 or len(questionnaire.get("profiles", [])) != 1:
        raise SystemExit("The active QuestionnaireResponse claim must be one exact closed profile")
    retraction_target_roles = protocol["lifecycle"]["retraction"]["targetRoles"]
    for role, rule in retraction_target_roles.items():
        if not re.fullmatch(r"[a-z][a-z0-9-]*", role) or not rule.get("resourceTypes"):
            raise SystemExit(f"{role}: invalid retraction target-role rule")
    priority = protocol["entryIdentity"]["resourceIdentifierPriority"]
    roles = {row["identifierRole"] for row in protocol["opaqueIdentity"]["identityKinds"]}
    if len(priority) != len(set(priority)) or any(role not in roles for role in priority):
        raise SystemExit("entryIdentity.resourceIdentifierPriority must be a unique closed role list")
    observation_claim = claims["observationAdapterClaim"]
    semantic = {measurement_canonical(catalogs, row) for row in catalogs.measurements["measurements"]}
    semantic.update(observation_claim.get("sharedSensorProfiles", []))
    semantic.update(entry["semanticProfile"] for entry in observation_claim.get("standardAdapterClaims", []))
    single_profile = set(claims["healthKitSingleProfileObservationClaims"]["profiles"])
    single_profile.update(claims["healthConnectPlatformExclusiveClaims"]["profiles"])
    single_profile.update(claims["sensorKitPlatformExclusiveClaims"]["profiles"])
    device_profiles = {claim["id"]: claim["profiles"][0] for claim in claims["activeDeviceClaims"]}
    return {
        "outputResourceTypes": active["entryResourcePolicy"]["outputResourceTypes"],
        "supportingResourceTypes": active["entryResourcePolicy"]["supportingResourceTypes"],
        "lifecycleResourceType": active["entryResourcePolicy"]["lifecycleResourceType"],
        "deviceModes": dict(sorted(device_modes.items())),
        "documentModes": sorted(document_modes),
        "questionnaireProfile": questionnaire["profiles"][0],
        "provenanceProfiles": sorted(
            {protocol["profiles"]["conversionProvenance"]}
            | {claim["profile"] for claim in claims["adapterConversionProvenanceClaims"]}
        ),
        "adapterObservationProfiles": sorted(observation_claim["adapterProfiles"]),
        "semanticObservationProfiles": sorted(semantic),
        "singleProfileObservationClaims": sorted(single_profile),
        "hybridObservationProfiles": sorted(claims["sensorKitHybridObservationClaims"]["profiles"]),
        "entryIdentifierPriority": priority,
        "retractionTargetRoles": dict(sorted(retraction_target_roles.items())),
        "applicationDeviceProfile": device_profiles["mobile-application-device"],
        "hostDeviceProfile": device_profiles["mobile-host-device"],
        "recordingDeviceProfile": device_profiles["mobile-recording-device"],
    }


NON_ADAPTER_SOURCES = {"mobile", "questionnaire", "sensor"}


def known_adapter_profiles(catalogs: Catalogs) -> set[str]:
    return {
        f"{package['canonical']}/StructureDefinition/{profile}"
        for package in catalogs.graph["packages"]
        if package["source"] not in NON_ADAPTER_SOURCES
        for profile in package["profiles"]
    }


def adapter_source_markers(catalogs: Catalogs) -> dict[str, list[str]]:
    """Every adapter source-marker extension URL to the adapter profiles that admit it."""
    known = known_adapter_profiles(catalogs)

    def prefixed(adapter: str) -> list[str]:
        prefix = f"{catalogs.graph['canonicalRoot']}/{adapter}/StructureDefinition/"
        return sorted(profile for profile in known if profile.startswith(prefix))

    providers = catalogs.providers
    provider_profiles = sorted(provider["observationProfile"] for provider in providers["providers"])
    markers = {
        catalogs.healthkit["sourceTypeExtension"]["url"]: prefixed("healthkit"),
        catalogs.health_connect["sourceTypeExtension"]["url"]: prefixed("health-connect"),
        providers["sourceTypeExtension"]["url"]: provider_profiles,
        providers["providerExtension"]["url"]: provider_profiles,
        catalogs.sensorkit["sourceTypeExtension"]["url"]: prefixed("sensorkit"),
    }
    for url, profiles in markers.items():
        if not profiles:
            raise SystemExit(f"{url}: the source marker admits no adapter profile")
    return markers


def adapter_conversion_provenance_claims(catalogs: Catalogs) -> list[dict[str, Any]]:
    rows = catalogs.claims["adapterConversionProvenanceClaims"]
    for row in rows:
        if not re.fullmatch(r"[a-z][a-z-]*", row["adapter"]) or not row.get("targetAdapterProfiles"):
            raise SystemExit(f"{row.get('profile')}: malformed adapter conversion Provenance claim")
    return sorted(rows, key=lambda row: row["adapter"])


def recording_formats(catalogs: Catalogs) -> dict[str, list[str]]:
    registry = catalogs.formats
    result: dict[str, list[str]] = {}
    for code, entry in registry["formats"].items():
        content_types = entry.get("contentTypes", [entry.get("contentType")])
        if not re.fullmatch(r"[a-z][a-z0-9-]*", code) or not all(isinstance(item, str) and item for item in content_types):
            raise SystemExit(f"{code}: malformed recording format registry entry")
        result[code] = list(content_types)
    return result


