def generate_test_vectors(catalogs: Catalogs) -> str:
    kinds = catalogs.protocol["opaqueIdentity"]["identityKinds"]
    vectors = catalogs.protocol["testVectors"]
    kind_names = [row["kind"] for row in kinds]
    identities = vectors.get("identities")
    invalid = vectors.get("invalidIdentities")
    systems = vectors.get("identitySystems")
    vector_kinds = [row["identityKind"] for row in identities] if isinstance(identities, list) else []
    if (
        set(vector_kinds) != set(kind_names)
        or not isinstance(invalid, list)
        or len(invalid) != 6
        or not isinstance(systems, list)
        or [row["identityKind"] for row in systems] != kind_names
    ):
        raise SystemExit(
            "The normative test vectors must cover every closed identity kind, retain all six invalid "
            "identity vectors and state one identifier system per kind"
        )
    return json.dumps(vectors, ensure_ascii=False, indent=2) + "\n"


def equality_fixtures(catalogs: Catalogs) -> dict[str, str]:
    corpus = catalogs.repository / "Conformance" / "corpora" / "receiver-lifecycle"
    events = json.loads((corpus / "events.json").read_text(encoding="utf-8"))
    sequences = json.loads((corpus / "sequences.json").read_text(encoding="utf-8"))
    selected = [sequence for sequence in sequences["sequences"] if sequence["id"] in EQUALITY_SEQUENCES]
    if [sequence["id"] for sequence in selected] != list(EQUALITY_SEQUENCES):
        raise SystemExit("The receiver-lifecycle corpus must carry the reformatted-replay and lexeme-replay sequences")
    aliases: list[str] = []
    for sequence in selected:
        for step in sequence["steps"]:
            if step["event"] not in aliases:
                aliases.append(step["event"])
    index = {
        "schemaVersion": 0,
        "contractLock": events["contractLock"],
        "equality": catalogs.protocol["payload"]["equality"],
        "events": {alias: events["events"][alias] for alias in aliases},
        "sequences": selected,
    }
    files = {"receiver-lifecycle/equality.json": json.dumps(index, ensure_ascii=False, indent=2) + "\n"}
    for alias in aliases:
        path = events["events"][alias]["path"]
        files[f"receiver-lifecycle/{path}"] = (corpus / path).read_text(encoding="utf-8")
    return files


